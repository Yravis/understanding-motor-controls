// Generates content/ch01/faults.yaml from the engine's fault definitions so cause/symptom text has ONE source.
// (tests/content-sync.test.ts asserts the committed file is up to date.)
import { writeFileSync } from 'node:fs';
import { stringify } from 'yaml';
import { faultDefs } from '../src/model/faults';
import { readYaml } from './lib/content';
import { paramsFromItems } from '../src/model/params';
import { minimalMeasurements } from '../src/model/scoring';

const SEC: Record<string, [string, number, number]> = {
  'open-coil': ['3.2', 24, 5], 'shorted-coil': ['3.2', 24, 5], 'welded-contact': ['3.2', 24, 5], 'high-resistance-contact': ['3.10', 29, 7],
  'loose-terminal': ['3.10', 29, 7], 'open-wire': ['3.18', 37, 9], 'float-no-nc-miswire': ['3.4', 26, 6], 'contact-on-x2-side': ['3.18', 37, 9],
  'wrong-timer-type': ['3.14', 35, 8], 'ss-offdelay-no-constant-supply': ['3.16', 36, 8], 'stuck-limit-switch': ['3.6', 27, 6], 'broken-shading-ring': ['3.2', 24, 5],
  'x1-ground-fault-clears-fuse': ['3.18', 37, 9], 'x1-ground-fault-high-impedance': ['3.18', 37, 9], 'foreign-voltage-bucket-off': ['1.1', 4, 1],
};
const NEC_430_74 = new Set(['contact-on-x2-side', 'x1-ground-fault-clears-fuse', 'x1-ground-fault-high-impedance']);
const nec43074 = () => ({
  nec: [{ edition: 2026, ref: '430.74', kind: 'rule', editionCheck: 'confirmed in NEC 2026 photo (p. 70-400)' }],
  excerpts: [{ ref: 'NEC 2026 430.74', covers: ['nec2026:430.74'], photo: 'review/source-photos/nec2026-p70-400-430.72-430.75.jpg', summary: '430.74 Electrical Arrangement of Control Circuits: with one control conductor grounded, a ground fault in the remote control circuit must not start the motor or bypass manual or automatic safety shutdown devices.' }],
});
export function faultItems() {
  const p = paramsFromItems(readYaml('content/ch01/devices.yaml').items);
  const defs = faultDefs(p);
  const cache = new Map<string, Map<string, string>>();
  return defs.map((f) => {
    const [sec, page, day] = SEC[f.id];
    const unit = Number(sec.split('.')[0]);
    return {
      id: `ch01.u${unit}.s${sec.replace('.', '-')}.fault.${f.id}`, type: 'fault', version: 1,
      book: { chapter: 1, unit, section: sec, page, pageStatus: 'toc-unverified', figure: null },
      nec: [], nema: [], ieee: [], excerpts: [], ...(NEC_430_74.has(f.id) ? nec43074() : {}), basis: 'illustrative', enforcedNote: null,
      other: [{ src: 'datasheet:TBD' }], bookAlignment: 'provisional',
      claim: f.cause,
      reviewerNotes: 'Expected readings are generated by the model (see review sheets); device values are typical/illustrative. Check that the symptom matches what the model shows and that the fix restores behavior.',
      body: { engineId: f.id, title: f.title, cause: f.cause, symptom: f.symptom, fixActions: f.fixActions, rootCause: f.rootCause, behaviorSame: !!f.behaviorSame, minMeasurements: minimalMeasurements(p, f, defs, cache), day },
    };
  });
}
if (process.argv[1]?.endsWith('gen-faults.ts')) {
  writeFileSync('content/ch01/faults.yaml', '# GENERATED by scripts/gen-faults.ts from src/model/faults.ts. Do not edit by hand.\n' + stringify({ items: faultItems() }, { lineWidth: 0 }));
  console.log('faults.yaml written');
}
